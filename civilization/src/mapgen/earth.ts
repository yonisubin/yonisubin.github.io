function inside(poly: Poly, lon: number, lat: number): boolean {
  let hit = false;
  for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
    const [xi, yi] = poly[i], [xj, yj] = poly[j];
    if (yi > lat !== yj > lat && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) hit = !hit;
  }
  return hit;
}

/** Is map tile (col, row) land on a w×h Earth map? */
export function earthLand(col: number, row: number, w: number, h: number): boolean {
  const lon = -180 + ((col + 0.5 + (row & 1) * 0.5) / w) * 360;
  const lat = 80 - ((row + 0.5) / h) * 155;
  return EARTH.some((p) => inside(p, lon, lat));
}
